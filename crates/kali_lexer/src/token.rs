use kali_common::Span;
use kali_error::diagnostic::Diagnostic;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TokenType {
    Plus,
    Minus,
    Star,
    StarStar,
    Slash,
    Caret,
    Percent,
    And,
    Or,
    Not,
    EqEquals,
    EqEqEq,
    Neq,
    NeqNeq,
    Lt,
    Gt,
    LtEq,
    GtEq,
    LtLt,
    GtGt,
    AmpEq,
    PipeEq,
    CaretEq,
    LtLtEq,
    GtGtEq,
    GtGtGtEq,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    PercentEq,
    StarStarEq,
    AndAnd,
    AndAndEq,
    OrOr,
    OrOrEq,
    QuestionDot,
    NullCoalesceEq,
    Arrow,
    Colon,
    Eq,
    Ampersand,
    Pipe,
    Tilde,
    At,
    Bang,
    Dot,
    DotDotDot,
    Hash,
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    LeftBracket,
    RightBracket,
    Semicolon,
    Comma,
    Backtick,
    Question,
    NullCoalesce,
    Eof,
    Comment,
    Identifier,
    NumericLiteral,
    StringLiteral,
    Template,
    Unknown,
    If,
    Else,
    For,
    While,
    Do,
    Switch,
    Case,
    Default,
    Break,
    Continue,
    Return,
    Throw,
    Try,
    Catch,
    Finally,
    Debugger,
    New,
    Function,
    Var,
    Let,
    Const,
    Class,
    Interface,
    Type,
    Enum,
    Import,
    Export,
    From,
    As,
    This,
    Super,
    Extends,
    Implements,
    Async,
    Await,
    Yield,
    InstanceOf,
    In,
    Of,
    True,
    False,
    Null,
    Undefined,
    Void,
    Delete,
    Typeof,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Token {
    pub kind: TokenType,
    pub value: String,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenType, value: String, span: Span) -> Self {
        Self { kind, value, span }
    }
}

pub struct LexerResult {
    pub tokens: Vec<Token>,
    pub diagnostics: Vec<Diagnostic>,
}
